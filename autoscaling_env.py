
import numpy as np
import gymnasium as gym
from gymnasium import spaces


class MultiTierAutoscalingEnv(gym.Env):
    """
    Three-tier cloud autoscaling simulator driven by NASA HTTP logs.

    NASA supplies real HTTP request counts.
    CPU, response time, SLA violations and infrastructure
    costs are estimates generated by this simulator.
    """

    metadata = {"render_modes": []}

    def __init__(self, workload, max_steps=1440, seed=42):
        super().__init__()

        self.workload = np.asarray(workload, dtype=np.float32)
        self.workload = self.workload[np.isfinite(self.workload)]
        self.workload = np.maximum(self.workload, 0.001)

        if len(self.workload) < 10:
            raise ValueError("Workload must contain at least 10 records.")

        self.max_steps = min(max_steps, len(self.workload))

        self.action_space = spaces.Discrete(7)

        self.observation_space = spaces.Box(
            low=0.0,
            high=10.0,
            shape=(5,),
            dtype=np.float32
        )

        # Per-replica request processing capacity.
        self.capacity = np.array(
            [7.0, 5.5, 4.5], dtype=np.float32
        )

        self.base_replicas = np.array([2, 2, 2])

        self.min_replicas = 1
        self.max_replicas = 10

        # Separate dataset position from episode progress.
        self.trace_start = 0
        self.episode_step = 0

        self.replicas = self.base_replicas.copy()
        self.last_metrics = {}

    def _metrics(self):

        index = (
            self.trace_start + self.episode_step
        ) % len(self.workload)

        rate = float(self.workload[index])

        tier_load = np.array([
            rate,
            rate * 1.15,
            rate * 1.30
        ])

        utilization = tier_load / (
            self.replicas * self.capacity
        )

        utilization = np.clip(
            utilization, 0, 2.5
        )

        tier_latency = (
            35
            + 85 * utilization
            + 260 * np.maximum(
                utilization - 0.70, 0
            ) ** 2 / 0.30
        )

        response_ms = float(
            np.sum(tier_latency) + 8
        )

        avg_cpu = float(
            np.mean(np.minimum(utilization, 1.0)) * 100
        )

        cost = float(
            np.sum(self.replicas) * 0.018
        )

        self.last_metrics = {
            "request_rate_rps": rate,
            "web_cpu_pct": float(utilization[0] * 100),
            "app_cpu_pct": float(utilization[1] * 100),
            "db_cpu_pct": float(utilization[2] * 100),
            "avg_cpu_pct": avg_cpu,
            "response_time_ms": response_ms,
            "cost": cost,
            "sla_violation": int(response_ms > 500),
            "web_replicas": int(self.replicas[0]),
            "app_replicas": int(self.replicas[1]),
            "db_replicas": int(self.replicas[2]),
            "total_replicas": int(np.sum(self.replicas))
        }

        return utilization, response_ms, rate

    def _obs(self):

        utilization, latency, rate = self._metrics()

        scale = max(
            float(np.percentile(self.workload, 95)),
            1.0
        )

        return np.array([
            np.clip(rate / scale, 0, 10),
            np.clip(utilization[0], 0, 2.5),
            np.clip(utilization[1], 0, 2.5),
            np.clip(utilization[2], 0, 2.5),
            np.clip(latency / 500, 0, 10)
        ], dtype=np.float32)

    def reset(self, seed=None, options=None):

        super().reset(seed=seed)

        max_start = len(self.workload) - self.max_steps

        self.trace_start = int(
            self.np_random.integers(
                0, max_start + 1
            )
        )

        self.episode_step = 0

        self.replicas = self.base_replicas.copy()

        return self._obs(), {}

    def step(self, action):

        # Actions: 0=no-op, then scale each tier up/down.
        if action in range(1, 7):

            tier = (action - 1) // 2

            direction = (
                1 if action % 2 == 1 else -1
            )

            self.replicas[tier] = int(
                np.clip(
                    self.replicas[tier] + direction,
                    self.min_replicas,
                    self.max_replicas
                )
            )

        utilization, latency, rate = self._metrics()

        cost = self.last_metrics["cost"]

        # Reward balances performance, SLA and cost.
        reward = (
            -(latency / 250.0)
            - (2.5 if latency > 500 else 0.0)
            - cost
        )

        self.episode_step += 1

        terminated = (
            self.episode_step >= self.max_steps
        )

        truncated = False

        if terminated:
            observation = np.zeros(
                5, dtype=np.float32
            )
        else:
            observation = self._obs()

        return (
            observation,
            float(reward),
            terminated,
            truncated,
            self.last_metrics.copy()
        )


def load_workload(
    csv_path="data/nasa_workload_1min.csv"
):

    import pandas as pd

    df = pd.read_csv(csv_path)

    if "request_rate_rps" not in df.columns:
        raise ValueError(
            "NASA workload CSV is missing request_rate_rps."
        )

    values = df["request_rate_rps"].astype(
        float
    ).to_numpy()

    values = np.nan_to_num(
        values,
        nan=0.0,
        posinf=0.0,
        neginf=0.0
    )

    return np.maximum(values, 0.02)
